//! Pins the Lisp declaration of every module function to its Rust defun.

mod common;

const MODULE: &str = include_str!("../src/module.rs");

/// Split `text` on the commas outside any brackets.
fn split_params(text: &str) -> Vec<&str> {
    let mut params = Vec::new();
    let (mut depth, mut start) = (0usize, 0usize);
    for (i, c) in text.char_indices() {
        match c {
            '<' | '(' | '[' => depth += 1,
            '>' | ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                params.push(&text[start..i]);
                start = i + 1;
            }
            _ => (),
        }
    }
    params.push(&text[start..]);
    params
        .into_iter()
        .map(str::trim)
        .filter(|p| !p.is_empty())
        .collect()
}

fn lisp_name(rust: &str) -> String {
    rust.replace('_', "-")
}

/// `(name, params)` of every `#[defun]` in module.rs, in source order. `&Env` is the module's own
/// argument, every other parameter is required, an `Option` only widens what it accepts.
fn defuns() -> Vec<(String, Vec<String>)> {
    let mut out = Vec::new();
    let mut rest = MODULE;
    while let Some(at) = rest.find("#[defun") {
        rest = &rest[at..];
        assert!(
            rest.starts_with("#[defun]"),
            "a #[defun(...)] attribute needs this generator extended"
        );
        let sig = &rest[rest.find("fn ").unwrap() + 3..];
        let open = sig.find('(').unwrap();
        let mut depth = 0;
        let close = sig
            .char_indices()
            .skip(open)
            .find(|&(_, c)| {
                match c {
                    '(' => depth += 1,
                    ')' => depth -= 1,
                    _ => (),
                }
                depth == 0
            })
            .unwrap()
            .0;
        let params = split_params(&sig[open + 1..close])
            .into_iter()
            .filter(|p| !p.ends_with("&Env"))
            .map(|p| lisp_name(p.split(':').next().unwrap().trim()))
            .collect();
        out.push((format!("ewm-{}", lisp_name(sig[..open].trim())), params));
        rest = &sig[close..];
    }
    out
}

fn fixture() -> String {
    let mut text = String::from(concat!(
        ";;; ewm-module.el --- Functions of the ewm-core module -*- lexical-binding: t -*-\n",
        ";; Generated by compositor/tests/module_decls.rs; regenerate with\n",
        ";;   EWM_UPDATE_FIXTURES=1 cargo test --test module_decls\n\n",
        ";; `declare-function' only counts in the file being compiled, so each\n",
        ";; file expands this macro rather than requiring the declarations.\n",
        "(defmacro ewm-module--declare ()\n",
        "  \"Declare every function of the ewm-core module to the byte-compiler.\"\n",
        "  '(progn",
    ));
    for (name, params) in defuns() {
        text.push_str(&format!(
            "\n     (declare-function {name} \"ewm-core\" ({}))",
            params.join(" ")
        ));
    }
    text.push_str("))\n\n(provide 'ewm-module)\n;;; ewm-module.el ends here\n");
    text
}
#[test]
fn declarations_match_the_defuns() {
    common::assert_generated("lisp/ewm-module.el", &fixture());
}
